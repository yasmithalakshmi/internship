# Level 7 - Question 9
# Perform all bitwise operations on two user-entered numbers.

num1 = int(input("Enter first number: "))
num2 = int(input("Enter second number: "))
print("AND:", num1 & num2)
print("OR:", num1 | num2)
print("XOR:", num1 ^ num2)
print("NOT first:", ~num1)
print("Left shift:", num1 << 1)
print("Right shift:", num2 >> 1)
