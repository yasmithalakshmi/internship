# Function practice group 1

def greet():
    print("Hello, Welcome to Python!")


def welcome(name):
    print(f"Welcome {name}!")


def add(a, b):
    return a + b


def subtract(a, b):
    return a - b


def multiply(a, b):
    return a * b


greet()
welcome("Yamini")
print("Sum:", add(10, 5))
print("Difference:", subtract(25, 7))
print("Product:", multiply(4, 6))
